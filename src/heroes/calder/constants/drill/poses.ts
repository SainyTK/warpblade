const runUpperBody = (phase: number) => {
  const step = (((phase * 2) % 1) + 1) % 1;
  const load = Math.sin(Math.PI * clamp(step / 0.46)) ** 1.2;
  const hipX = -0.3 + 0.3 * Math.sin(phase * TAU);
  const hipY = -10.6 + 1.2 * load;
  const swing = Math.cos(phase * TAU);
  const neckX = hipX + 5.2 + 1.2 * load;
  const neckY = hipY - 8.9;
  return pose({
    hx: hipX,
    hy: hipY,
    nx: neckX,
    ny: neckY,
    cb: 0.9 + 0.4 * load,
    fx: neckX + 3 + 0.6 * load,
    fy: neckY + 3.4 + 1.1 * load,
    sa: lerp(-2.62, -2.48, load),
    bx: neckX - 0.5 + 6.8 * swing,
    by: neckY + 6.2 - 1.4 * swing,
    be: 1,
  });
};

