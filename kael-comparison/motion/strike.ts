function ground(
  time: number,
  beat: string,
  root: number,
  feet: readonly [number, number],
  keys: Partial<Pose>,
  contacts: readonly [boolean, boolean] = [true, true],
  impact = false,
): Key {
  return [
    time,
    { beat, root, lift: 0, contacts, impact, pose: pose({ ...keys, ffx: feet[0] - root, bfx: feet[1] - root }) },
  ];
}

